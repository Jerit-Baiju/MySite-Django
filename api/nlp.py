"""20. Text Coherence Using Sentence Similarity"""

from sklearn.feature_extraction.text import TfidfVectorizer
from sklearn.metrics.pairwise import cosine_similarity

sentences = [
    "Machine learning is used in healthcare.",
    "Machine learning helps doctors detect diseases.",
    "Doctors use medical data for diagnosis.",
]

vectorizer = TfidfVectorizer()

vectors = vectorizer.fit_transform(sentences)

for i in range(len(sentences) - 1):

    similarity = cosine_similarity(vectors[i], vectors[i + 1])

    print("Sentence", i + 1, "and Sentence", i + 2, "=", similarity[0][0])


