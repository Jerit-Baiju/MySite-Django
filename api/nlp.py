"""WordNet — Synonyms, Antonyms, Hypernyms and Hyponyms"""

from nltk.corpus import wordnet as wn

word = "bank"

synsets = wn.synsets(word)

print("Synsets:")
for s in synsets:
    print(s.name())

print("\nSynonyms:")
for s in synsets:
    for lemma in s.lemmas():
        print(lemma.name())

print("\nAntonyms:")
for s in synsets:
    for lemma in s.lemmas():
        for ant in lemma.antonyms():
            print(ant.name())

print("\nHypernyms:")
print(synsets[0].hypernyms())

print("\nHyponyms:")
print(synsets[0].hyponyms())

